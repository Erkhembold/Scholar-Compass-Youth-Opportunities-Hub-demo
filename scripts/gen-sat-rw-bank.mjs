// Generates src/data/satRwBank.js from data/sat_rw_bank_v1.csv (source of truth).
// Run: node scripts/gen-sat-rw-bank.mjs   (add --check to verify without writing)
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const csvPath = path.join(root, "data/sat_rw_bank_v1.csv");
const outPath = path.join(root, "src/data/satRwBank.js");

export function parseCsv(text) {
  const rows = []; let row = [], f = "", q = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (q) {
      if (c === '"') { if (text[i + 1] === '"') { f += '"'; i++; } else q = false; }
      else f += c;
    } else if (c === '"') q = true;
    else if (c === ",") { row.push(f); f = ""; }
    else if (c === "\n" || c === "\r") {
      if (c === "\r" && text[i + 1] === "\n") i++;
      row.push(f); f = ""; rows.push(row); row = [];
    } else f += c;
  }
  if (f !== "" || row.length) { row.push(f); rows.push(row); }
  return rows.filter((r) => r.some((x) => x !== ""));
}

const DOMAIN_TO_CATEGORY = {
  "Craft and Structure": "craft-and-structure",
  "Information and Ideas": "information-and-ideas",
  "Standard English Conventions": "standard-english-conventions",
  "Expression of Ideas": "expression-of-ideas",
};

export function buildBank(text) {
  const [header, ...rows] = parseCsv(text.replace(/^﻿/, ""));
  return rows.map((r) => {
    const o = Object.fromEntries(header.map((h, i) => [h.trim(), r[i]]));
    const category = DOMAIN_TO_CATEGORY[o.domain];
    if (!category) throw new Error(`Unknown domain ${o.domain} (${o.id})`);
    return {
      category,
      q: {
        id: o.id,
        passage: o.passage.trim(), // only leading/trailing whitespace trimmed
        prompt: o.question,
        options: ["A", "B", "C", "D"].map((id) => ({ id, text: o[id] })),
        answer: o.correct_answer.trim(),
        explanation: o.explanation,
        skill: o.skill,
        difficulty: o.difficulty,
        questionType: o.question_type,
      },
    };
  });
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const bank = buildBank(fs.readFileSync(csvPath, "utf8"));
  const byCat = {};
  for (const { category, q } of bank) (byCat[category] ||= []).push(q);
  const out =
`// GENERATED by scripts/gen-sat-rw-bank.mjs from data/sat_rw_bank_v1.csv — do not edit by hand.
// 100 original SAT-style Reading & Writing questions written for ScholarCompass.
// Not official College Board material.
export const SAT_RW_BANK_V1 = ${JSON.stringify(byCat, null, 2)};
`;
  if (process.argv.includes("--check")) {
    if (fs.readFileSync(outPath, "utf8") !== out) { console.error("satRwBank.js is out of date"); process.exit(1); }
  } else fs.writeFileSync(outPath, out);
  console.log("questions:", bank.length);
}
